// End-to-end self-checking testbench for snn_inference_core (RTL milestone 12).
// Run from fpga/tb (vector paths are relative):
//   vlog -sv ../rtl/snn_params_pkg.sv ../rtl/sync_rom.sv ../rtl/pixel_buffer.sv ../rtl/l1_mac.sv \
//            ../rtl/l1_neuron_engine.sv ../rtl/cur1_ram.sv ../rtl/l1_current_sweep.sv ../rtl/mem1_ram.sv \
//            ../rtl/decay_19_20.sv ../rtl/lif_core.sv ../rtl/l1_lif_sweep.sv ../rtl/l2_acc.sv \
//            ../rtl/l2_current_engine.sv ../rtl/l2_lif_sweep.sv ../rtl/output_spike_counters.sv \
//            ../rtl/argmax10.sv ../rtl/snn_inference_controller.sv ../rtl/snn_inference_core.sv \
//            tb_snn_inference_core.sv
//   vsim -c work.tb_snn_inference_core -do "run -all; quit -f"
//
// The only inference command is `start`; every intermediate start/clear is generated by the
// controller. Monitors sample at negedge (each one-clock pulse is seen exactly once).
// Stimulus is applied 1 ns after posedge.
`timescale 1ns/1ps

module tb_snn_inference_core;
  import snn_params_pkg::*;

  localparam int NIMG  = 22;
  localparam int NSTEP = NUM_STEPS;

  logic clk = 1'b0;
  always #5 clk = ~clk;
  logic rst;

  logic        pixel_we;
  logic [9:0]  pixel_waddr;
  logic [7:0]  pixel_wdata;
  logic        start_main, start_spam, start;
  assign start = start_main | start_spam;
  logic        busy, done;
  logic [3:0]  predicted_digit;
  logic [SPIKE_COUNT_WIDTH-1:0] counts [0:OUTPUT_SIZE-1];

  snn_inference_core dut (.clk(clk), .rst(rst), .pixel_we(pixel_we), .pixel_waddr(pixel_waddr),
                          .pixel_wdata(pixel_wdata), .start(start), .busy(busy), .done(done),
                          .predicted_digit(predicted_digit), .counts(counts));

  // ---------------- vectors ----------------
  logic [7:0]   pix  [0:NIMG*784-1];
  logic [35:0]  cur1 [0:NIMG*256-1];
  logic [255:0] hsv  [0:NIMG*NSTEP-1];
  logic [35:0]  cur2 [0:NIMG*NSTEP*10-1];
  int           stspk [0:NIMG*NSTEP-1];
  int           stc   [0:NIMG*NSTEP*10-1];
  int           fpred [0:NIMG-1];
  int           fcnt  [0:NIMG*10-1];
  int           v [0:10];
  int           fd, rc;

  // ---------------- per-inference event counters (reset at accepted start) ----------------
  int n_l1c_start, n_l1_clr, n_l2_clr, n_cnt_clr, n_l1s_start, n_l1s_done, n_l2c_start, n_l2c_done;
  int n_l2s_start, n_l2s_done, n_count, n_done;
  bit running;
  int cur_img;

  // ---------------- totals ----------------
  int t_images, t_pixel_loads, t_l1c, t_l1s, t_l2c, t_l2s, t_count, t_inf;
  int t_cum_cmp, t_final_cmp, t_pred_cmp, t_hs_cmp, t_cur2_cmp, t_cur1_cmp, t_step_chk;
  int f_cum, f_final, f_pred, f_hs, f_cur2, f_cur1, f_ctrl, f_order, f_ts, f_lat, f_busy, f_extra;
  int sb_tests, sb_ignored, b2b_tests, b2b_fail, rst_tests, rst_fail;
  int min_lat, max_lat, lat_checks;
  int fails;
  int exp_ts;

  function automatic int ci(input int img, input int t, input int k);
    return (img*NSTEP + t)*10 + k;
  endfunction

  // ---------------- latency measurement ----------------
  int lat;
  bit lat_run;
  always @(posedge clk) begin
    if (rst) lat_run <= 1'b0;
    else if (!lat_run && start && !busy) begin lat_run <= 1'b1; lat <= 0; end
    else if (lat_run) begin
      lat <= lat + 1;
      if (done) begin
        lat_run <= 1'b0;
        lat_checks++;
        if (lat_checks == 1 || lat - 1 < min_lat) min_lat <= lat - 1;
        if (lat_checks == 1 || lat - 1 > max_lat) max_lat <= lat - 1;
      end
    end
  end

  // ---------------- control-pulse and ordering monitor ----------------
  task automatic ctrl_fail(input string m);
    f_order++;
    if (f_order <= 10) $display("ORDER FAIL img=%0d: %s (cnt=%0d l1s=%0d/%0d l2c=%0d/%0d l2s=%0d/%0d)", cur_img, m,
                                n_count, n_l1s_start, n_l1s_done, n_l2c_start, n_l2c_done, n_l2s_start, n_l2s_done);
  endtask

  int pend_check = -1;     // step index whose cumulative counts must be checked at the next negedge
  always @(negedge clk) begin
    if (rst) begin
      running = 1'b0;
      pend_check = -1;
    end else begin
      // cumulative-count check one clock after the count edge
      if (pend_check >= 0 && running) begin
        for (int k = 0; k < OUTPUT_SIZE; k++) begin
          t_cum_cmp++;
          if (int'(counts[k]) !== stc[ci(cur_img, pend_check, k)]) begin
            f_cum++;
            if (f_cum <= 10) $display("CUM FAIL img=%0d t=%0d k=%0d got=%0d exp=%0d", cur_img, pend_check, k, counts[k],
                                      stc[ci(cur_img, pend_check, k)]);
          end
        end
        pend_check = -1;
      end
      if (running) begin
        if (dut.l1_current_start) begin n_l1c_start++; end
        if (dut.l1_clear_state)   n_l1_clr++;
        if (dut.l2_clear_state)   n_l2_clr++;
        if (dut.clear_counts)     n_cnt_clr++;
        if (dut.l1_current_done) begin
          for (int j = 0; j < 256; j++) begin
            t_cur1_cmp++;
            if (dut.u_l1c.u_cur1.mem[j] !== cur1[cur_img*256 + j][34:0]) begin
              f_cur1++;
              if (f_cur1 <= 10) $display("CUR1 FAIL img=%0d j=%0d got=%h exp=%h", cur_img, j, dut.u_l1c.u_cur1.mem[j], cur1[cur_img*256 + j][34:0]);
            end
          end
        end
        if (dut.l1_start_step) begin
          if (!(n_l1s_start == n_count && n_l1s_done == n_count && n_l1c_start == 1)) ctrl_fail("l1_start_step out of order");
          if (int'(dut.timestep) !== n_count) begin f_ts++; $display("TIMESTEP FAIL img=%0d got=%0d exp=%0d", cur_img, dut.timestep, n_count); end
          n_l1s_start++;
        end
        if (dut.l1_step_done) begin
          n_l1s_done++;
          if (n_l1s_done != n_l1s_start) ctrl_fail("l1_step_done without matching start");
          if (n_l1s_done >= 1 && n_l1s_done <= NSTEP) begin
            t_hs_cmp++;
            if (dut.hidden_spikes !== hsv[cur_img*NSTEP + n_l1s_done - 1]) begin
              f_hs++;
              if (f_hs <= 10) $display("HIDDEN SPIKES FAIL img=%0d t=%0d", cur_img, n_l1s_done - 1);
            end
          end
        end
        if (dut.l2_current_start) begin
          if (!(n_l1s_done == n_l1s_start && n_l2c_start == n_count && n_l2c_done == n_count)) ctrl_fail("l2_current_start out of order");
          n_l2c_start++;
        end
        if (dut.l2_current_done) begin
          n_l2c_done++;
          if (n_l2c_done != n_l2c_start) ctrl_fail("l2_current_done without matching start");
          if (n_l2c_done >= 1 && n_l2c_done <= NSTEP)
            for (int k = 0; k < OUTPUT_SIZE; k++) begin
              t_cur2_cmp++;
              if (dut.cur2[k] !== cur2[ci(cur_img, n_l2c_done - 1, k)][32:0]) begin
                f_cur2++;
                if (f_cur2 <= 10) $display("CUR2 FAIL img=%0d t=%0d k=%0d got=%h exp=%h", cur_img, n_l2c_done - 1, k, dut.cur2[k],
                                           cur2[ci(cur_img, n_l2c_done - 1, k)][32:0]);
              end
            end
        end
        if (dut.l2_start_step) begin
          if (!(n_l2c_done == n_l2c_start && n_l2s_start == n_count && n_l2s_done == n_count)) ctrl_fail("l2_start_step out of order");
          n_l2s_start++;
        end
        if (dut.l2_step_done) begin
          n_l2s_done++;
          if (n_l2s_done != n_l2s_start) ctrl_fail("l2_step_done without matching start");
        end
        if (dut.count_enable) begin
          if (!(n_l2s_done == n_l2s_start && n_l2s_start == n_count + 1)) ctrl_fail("count_enable out of order");
          if (n_count < NSTEP) begin
            t_step_chk++;
            if (dut.output_spikes !== stspk[cur_img*NSTEP + n_count][OUTPUT_SIZE-1:0]) begin
              f_hs++;
              if (f_hs <= 10) $display("OUTPUT SPIKES FAIL img=%0d t=%0d got=%b exp=%b", cur_img, n_count, dut.output_spikes,
                                       stspk[cur_img*NSTEP + n_count][OUTPUT_SIZE-1:0]);
            end
            pend_check = n_count;
          end
          n_count++;
        end
        if (done) begin
          n_done++;
          running = 1'b0;
          if (busy) begin f_busy++; $display("busy high at done"); end
          // final checks
          t_inf++;
          if (n_l1c_start != 1 || n_l1_clr != 1 || n_l2_clr != 1 || n_cnt_clr != 1 || n_l1s_start != NSTEP ||
              n_l1s_done != NSTEP || n_l2c_start != NSTEP || n_l2c_done != NSTEP || n_l2s_start != NSTEP ||
              n_l2s_done != NSTEP || n_count != NSTEP || n_done != 1) begin
            f_ctrl++;
            $display("PULSE COUNT FAIL img=%0d: l1c=%0d l1clr=%0d l2clr=%0d cclr=%0d l1s=%0d/%0d l2c=%0d/%0d l2s=%0d/%0d cnt=%0d done=%0d",
                     cur_img, n_l1c_start, n_l1_clr, n_l2_clr, n_cnt_clr, n_l1s_start, n_l1s_done, n_l2c_start, n_l2c_done,
                     n_l2s_start, n_l2s_done, n_count, n_done);
          end
          t_l1c += n_l1c_start; t_l1s += n_l1s_start; t_l2c += n_l2c_start; t_l2s += n_l2s_start; t_count += n_count;
          for (int k = 0; k < OUTPUT_SIZE; k++) begin
            t_final_cmp++;
            if (int'(counts[k]) !== fcnt[cur_img*10 + k]) begin
              f_final++;
              $display("FINAL COUNT FAIL img=%0d k=%0d got=%0d exp=%0d", cur_img, k, counts[k], fcnt[cur_img*10 + k]);
            end
          end
          t_pred_cmp++;
          if (int'(predicted_digit) !== fpred[cur_img]) begin
            f_pred++;
            $display("PREDICTION FAIL img=%0d got=%0d exp=%0d (counts %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d)", cur_img,
                     predicted_digit, fpred[cur_img], counts[0], counts[1], counts[2], counts[3], counts[4], counts[5],
                     counts[6], counts[7], counts[8], counts[9]);
          end
        end
      end
    end
  end

  // an accepted start (sampled at posedge, busy low) opens a new inference record
  always @(posedge clk) begin
    if (!rst && start && !busy) begin
      n_l1c_start = 0; n_l1_clr = 0; n_l2_clr = 0; n_cnt_clr = 0; n_l1s_start = 0; n_l1s_done = 0;
      n_l2c_start = 0; n_l2c_done = 0; n_l2s_start = 0; n_l2s_done = 0; n_count = 0; n_done = 0;
      running = 1'b1;
    end
  end

  // ---------------- start-while-busy injector ----------------
  bit spam_en;
  bit sp_l1c, sp_early, sp_mid, sp_last;
  always @(negedge clk) begin
    start_spam <= 1'b0;
    if (spam_en && running && !rst) begin
      if (!sp_l1c && dut.u_l1c.busy && dut.u_l1c.nidx == 8'd100) begin sp_l1c = 1'b1; start_spam <= 1'b1; sb_ignored++; end
      else if (!sp_early && dut.u_ctrl.timestep == 5'd1 && dut.u_ctrl.state == 4'd8) begin sp_early = 1'b1; start_spam <= 1'b1; sb_ignored++; end
      else if (!sp_mid && dut.u_ctrl.timestep == 5'd12 && dut.u_ctrl.state == 4'd10) begin sp_mid = 1'b1; start_spam <= 1'b1; sb_ignored++; end
      else if (!sp_last && dut.u_ctrl.timestep == 5'd24 && dut.u_ctrl.state == 4'd6) begin sp_last = 1'b1; start_spam <= 1'b1; sb_ignored++; end
    end
  end

  // ---------------- tasks ----------------
  task automatic do_reset();
    rst = 1'b1; start_main = 1'b0; pixel_we = 1'b0; pixel_waddr = '0; pixel_wdata = '0;
    repeat (3) @(posedge clk);
    #1 rst = 1'b0;
    @(posedge clk); #1;
  endtask

  task automatic load_image(input int im);
    for (int i = 0; i < 784; i++) begin
      pixel_we = 1'b1; pixel_waddr = 10'(i); pixel_wdata = pix[im*784 + i];
      @(posedge clk); #1;
      t_pixel_loads++;
    end
    pixel_we = 1'b0;
    cur_img = im;
  endtask

  task automatic pulse_start();
    start_main = 1'b1;
    @(posedge clk); #1 start_main = 1'b0;
  endtask

  task automatic wait_done(input int maxclk);
    int c = 0;
    while (!done && c < maxclk) begin @(posedge clk); #1; c++; end
    if (c >= maxclk) begin f_lat++; $display("TIMEOUT waiting for done (img %0d)", cur_img); end
    @(posedge clk); #1;
  endtask

  task automatic run_image(input int im, input bit spam);
    load_image(im);
    sp_l1c = 0; sp_early = 0; sp_mid = 0; sp_last = 0; spam_en = spam;
    pulse_start();
    wait_done(400000);
    spam_en = 1'b0;
    if (spam) begin
      sb_tests++;
      if (!(sp_l1c && sp_early && sp_mid && sp_last)) begin f_extra++; $display("start-while-busy injector did not fire"); end
    end
    t_images++;
    repeat (4) begin @(posedge clk); #1; end
  endtask

  task automatic reset_mid(input int im, input int where_);
    int dones_before = t_inf;
    load_image(im);
    spam_en = 1'b0;
    pulse_start();
    if (where_ == 0) begin
      while (!(dut.u_l1c.busy && dut.u_l1c.nidx == 8'd50)) begin @(posedge clk); #1; end
    end else begin
      while (!(dut.u_ctrl.timestep == 5'(where_) && dut.u_ctrl.state == 4'd8)) begin @(posedge clk); #1; end
    end
    rst = 1'b1;
    @(posedge clk); #1;
    @(posedge clk); #1;
    rst = 1'b0;
    rst_tests++;
    if (busy !== 1'b0 || dut.u_ctrl.state !== 4'd0) begin rst_fail++; $display("reset: controller not idle"); end
    // no done pulse for the aborted inference
    for (int i = 0; i < 3000; i++) begin
      @(posedge clk); #1;
      if (done !== 1'b0) begin rst_fail++; $display("done pulse after reset-abort"); end
    end
    if (t_inf != dones_before) begin rst_fail++; $display("inference counted for an aborted run"); end
  endtask

  initial begin
    t_images = 0; t_pixel_loads = 0; t_l1c = 0; t_l1s = 0; t_l2c = 0; t_l2s = 0; t_count = 0; t_inf = 0;
    t_cum_cmp = 0; t_final_cmp = 0; t_pred_cmp = 0; t_hs_cmp = 0; t_cur2_cmp = 0; t_cur1_cmp = 0; t_step_chk = 0;
    f_cum = 0; f_final = 0; f_pred = 0; f_hs = 0; f_cur2 = 0; f_cur1 = 0; f_ctrl = 0; f_order = 0; f_ts = 0;
    f_lat = 0; f_busy = 0; f_extra = 0; sb_tests = 0; sb_ignored = 0; b2b_tests = 0; b2b_fail = 0;
    rst_tests = 0; rst_fail = 0; lat_checks = 0; min_lat = 0; max_lat = 0; spam_en = 0; running = 0; cur_img = 0;
    start_spam = 1'b0; start_main = 1'b0; rst = 1'b1;

    $readmemh("vectors/fi_pix.txt", pix);
    $readmemh("vectors/fi_cur1.txt", cur1);
    $readmemh("vectors/fi_hs.txt", hsv);
    $readmemh("vectors/fi_cur2.txt", cur2);
    fd = $fopen("vectors/fi_step.txt", "r");
    if (fd == 0) begin $display("cannot open fi_step.txt"); $finish; end
    for (int i = 0; i < NIMG*NSTEP; i++) begin
      rc = $fscanf(fd, "%h %h %h %h %h %h %h %h %h %h %h", v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7], v[8], v[9], v[10]);
      if (rc != 11) begin $display("fi_step read error line %0d", i); $finish; end
      stspk[i] = v[0];
      for (int k = 0; k < 10; k++) stc[i*10 + k] = v[k+1];
    end
    $fclose(fd);
    fd = $fopen("vectors/fi_final.txt", "r");
    for (int i = 0; i < NIMG; i++) begin
      rc = $fscanf(fd, "%h %h %h %h %h %h %h %h %h %h %h", v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7], v[8], v[9], v[10]);
      if (rc != 11) begin $display("fi_final read error line %0d", i); $finish; end
      fpred[i] = v[0];
      for (int k = 0; k < 10; k++) fcnt[i*10 + k] = v[k+1];
    end
    $fclose(fd);

    do_reset();

    // 22 back-to-back inferences on one instance (no reset between): MNIST 0..19, all-zero, all-255.
    // Images 0, 7 and 21 also receive start-while-busy pulses at four moments.
    for (int im = 0; im < NIMG; im++) begin
      run_image(im, (im == 0) || (im == 7) || (im == 21));
      if (im > 0) b2b_tests++;
    end
    // explicit A -> B -> A back-to-back with different images
    run_image(20, 1'b0); run_image(3, 1'b0); run_image(20, 1'b0); b2b_tests += 3;

    // reset in the middle of an inference, then a fresh image on the same instance
    reset_mid(5, 0);
    run_image(8, 1'b0);
    reset_mid(9, 10);
    run_image(1, 1'b0);
    reset_mid(2, 24);
    run_image(21, 1'b0);

    fails = f_cum + f_final + f_pred + f_hs + f_cur2 + f_cur1 + f_ctrl + f_order + f_ts + f_lat + f_busy + f_extra +
            rst_fail + b2b_fail;
    $display("---------------- RESULTS ----------------");
    $display("complete inferences=%0d (images run=%0d), pixel loads=%0d", t_inf, t_images, t_pixel_loads);
    $display("Layer-1 current sweeps=%0d, Layer-1 LIF steps=%0d, Layer-2 current runs=%0d, Layer-2 LIF steps=%0d, count pulses=%0d",
             t_l1c, t_l1s, t_l2c, t_l2s, t_count);
    $display("cumulative-count comparisons=%0d failures=%0d", t_cum_cmp, f_cum);
    $display("final-count comparisons=%0d failures=%0d; prediction comparisons=%0d failures=%0d", t_final_cmp, f_final, t_pred_cmp, f_pred);
    $display("debug checkpoints: cur1=%0d failures=%0d, hidden-spike vectors=%0d, output-spike vectors=%0d (failures=%0d), cur2=%0d failures=%0d",
             t_cur1_cmp, f_cur1, t_hs_cmp, t_step_chk, f_hs, t_cur2_cmp, f_cur2);
    $display("control-pulse count failures=%0d, ordering failures=%0d, timestep-order failures=%0d, busy-at-done failures=%0d",
             f_ctrl, f_order, f_ts, f_busy);
    $display("start-while-busy inferences=%0d (injected ignored starts=%0d), extra failures=%0d", sb_tests, sb_ignored, f_extra);
    $display("back-to-back image transitions=%0d, failures=%0d", b2b_tests, b2b_fail);
    $display("reset-mid-inference tests=%0d failures=%0d", rst_tests, rst_fail);
    $display("accepted start -> done latency: min=%0d max=%0d over %0d inferences", min_lat, max_lat, lat_checks);
    $display("total failures=%0d", fails);
    if (fails == 0) $display("PASS tb_snn_inference_core");
    else            $display("FAIL tb_snn_inference_core");
    $finish;
  end

  initial begin
    #150000000;
    $display("TIMEOUT");
    $finish;
  end
endmodule
